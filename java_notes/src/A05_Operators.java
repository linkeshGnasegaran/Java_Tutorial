// Operators
public class A05_Operators {
    public static void main(String[] args) {
        int m = 10, n = 5;
        System.out.println("m + n = " + (m + n));
        System.out.println("m > n ? " + (m > n));
        System.out.println("Logical && : " + (m == 10 && n == 5));
        m += 3;
        System.out.println("After += 3: " + m);
    }
}
